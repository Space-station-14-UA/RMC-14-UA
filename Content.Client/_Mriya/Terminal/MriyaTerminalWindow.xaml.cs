using System.Numerics;
using Content.Client.Stylesheets;
using Content.Shared._Mriya.Terminal;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.ResourceManagement;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Graphics;
using Robust.Shared.IoC;
using Robust.Shared.Maths;
using Robust.Shared.Timing;
using Robust.Shared.Utility;

namespace Content.Client._Mriya.Terminal;

[GenerateTypedNameReferences]
public sealed partial class MriyaTerminalWindow : DefaultWindow
{
    public event Action<string>? OnMessageEntered;

    private static readonly Color Mint = Color.FromHex("#BFF3D4");
    private static readonly Color MintDim = Color.FromHex("#8FD9A8");
    private static readonly Color SeparatorColor = Color.FromHex("#4F8A63");
    private static readonly Color SenderColor = Color.FromHex("#D7FFE3");

    private readonly Font _font;
    private readonly Font _fontBold;
    private readonly Font _fontSmall;
    private readonly StyleBoxFlat _buttonBox;
    private readonly StyleBoxFlat _lineEditBox;

    private List<string> _currentMessages = new();
    private float _animationProgress;
    private bool _isAnimating;
    private bool _scrollHistoryToBottom;
    private const float CharactersPerSecond = 50f;

    public MriyaTerminalWindow()
    {
        RobustXamlLoader.Load(this);

        var cache = IoCManager.Resolve<IResourceCache>();
        _font = new VectorFont(cache.GetResource<FontResource>("/Fonts/RobotoMono/RobotoMono-Regular.ttf"), 12);
        _fontBold = new VectorFont(cache.GetResource<FontResource>("/Fonts/RobotoMono/RobotoMono-Bold.ttf"), 12);
        _fontSmall = new VectorFont(cache.GetResource<FontResource>("/Fonts/RobotoMono/RobotoMono-Regular.ttf"), 10);

        _buttonBox = MakeBox(Color.FromHex("#07240F"), Color.FromHex("#12602E"), 8, 4);
        _lineEditBox = MakeBox(Color.FromHex("#06180D"), Color.FromHex("#12602E"), 6, 3);

        HistoryTitleLabel.FontOverride = _font;
        HistoryTitleLabel.FontColorOverride = Mint;

        OperatorLabel.FontOverride = _fontSmall;
        OperatorLabel.FontColorOverride = MintDim;

        OperatorNameLabel.FontOverride = _fontBold;
        OperatorNameLabel.FontColorOverride = Mint;

        OperatorJobLabel.FontOverride = _fontSmall;
        OperatorJobLabel.FontColorOverride = MintDim;

        foreach (var button in new[] { HistoryButton, BackButton, SendButton })
        {
            button.StyleBoxOverride = _buttonBox;
            button.Label.FontOverride = _fontBold;
            button.Label.FontColorOverride = Mint;
        }

        InputBar.StyleBoxOverride = _lineEditBox;
        InputBar.StyleClasses.Add(StyleNano.StyleClassMriyaTerminalLineEdit);

        InputBar.OnTextEntered += _ => SendMessage();
        SendButton.OnPressed += _ => SendMessage();
        HistoryButton.OnPressed += _ => ShowHistory(true);
        BackButton.OnPressed += _ => ShowHistory(false);
    }

    private static StyleBoxFlat MakeBox(Color background, Color border, float horizontal, float vertical)
    {
        var box = new StyleBoxFlat
        {
            BackgroundColor = background,
            BorderColor = border,
            BorderThickness = new Thickness(1),
        };

        box.ContentMarginLeftOverride = horizontal;
        box.ContentMarginRightOverride = horizontal;
        box.ContentMarginTopOverride = vertical;
        box.ContentMarginBottomOverride = vertical;
        return box;
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);

        if (_scrollHistoryToBottom)
        {
            _scrollHistoryToBottom = false;
            HistoryScroll.SetScrollValue(new Vector2(0, 1000000));
        }

        if (!_isAnimating || _currentMessages.Count == 0)
            return;

        var (_, lastMessage) = SplitMessage(_currentMessages[^1]);
        _animationProgress += args.DeltaSeconds * CharactersPerSecond;

        if (_animationProgress >= lastMessage.Length)
        {
            _animationProgress = lastMessage.Length;
            _isAnimating = false;
        }

        UpdateDisplay(InputContainer.Visible, (int) _animationProgress);
    }

    private void SendMessage()
    {
        if (string.IsNullOrWhiteSpace(InputBar.Text))
            return;

        OnMessageEntered?.Invoke(InputBar.Text.ToUpper());
        InputBar.Text = string.Empty;
    }

    private void ShowHistory(bool show)
    {
        HistoryPage.Visible = show;
        MainPage.Visible = !show;

        if (!show)
            return;

        UpdateHistoryDisplay();
        _scrollHistoryToBottom = true;
    }

    public void SetState(MriyaTerminalState state)
    {
        InputContainer.Visible = state.IsInput;

        var name = string.IsNullOrWhiteSpace(state.AuthorizedName)
            ? "НЕВІДОМИЙ"
            : state.AuthorizedName.ToUpperInvariant();
        var job = string.IsNullOrWhiteSpace(state.AuthorizedJob)
            ? "—"
            : state.AuthorizedJob.ToUpperInvariant();
        OperatorNameLabel.Text = name;
        OperatorJobLabel.Text = job;
        OperatorNameLabel.ToolTip = state.AuthorizedName;
        OperatorJobLabel.ToolTip = state.AuthorizedJob;

        // Check if we have new messages to animate
        var hasNew = state.Messages.Count > _currentMessages.Count ||
                     (state.Messages.Count > 0 && _currentMessages.Count > 0 && state.Messages[^1] != _currentMessages[^1]);

        _currentMessages = new List<string>(state.Messages);

        if (hasNew)
        {
            _animationProgress = 0f;
            _isAnimating = true;
        }
        else if (!_isAnimating)
        {
            UpdateDisplay(state.IsInput, -1);
        }

        UpdateHistoryDisplay();
    }

    private void UpdateDisplay(bool isInput, int animationLength)
    {
        var msg = new FormattedMessage();

        if (isInput)
        {
            if (_currentMessages.Count > 0)
                AppendMessage(msg, _currentMessages[^1], animationLength);
        }
        else
        {
            for (var i = 0; i < _currentMessages.Count; i++)
            {
                var length = i == _currentMessages.Count - 1 ? animationLength : -1;
                AppendMessage(msg, _currentMessages[i], length);
            }
        }

        MessageHistory.SetMessage(msg);
        MessageHistory.MaxWidth = 470;
        MessageHistory.InvalidateMeasure();

        Scroll.SetScrollValue(new Vector2(0, 1000000));
    }

    private void UpdateHistoryDisplay()
    {
        var msg = new FormattedMessage();

        foreach (var message in _currentMessages)
        {
            AppendMessage(msg, message);
        }

        HistoryMessages.SetMessage(msg);
        HistoryMessages.MaxWidth = 470;
        HistoryMessages.InvalidateMeasure();
    }

    private static void AppendMessage(FormattedMessage msg, string raw, int animationLength = -1)
    {
        var (sender, body) = SplitMessage(raw);

        if (animationLength >= 0 && animationLength < body.Length)
            body = body[..animationLength];

        var senderText = FormattedMessage.EscapeText(sender.ToUpperInvariant());
        var bodyText = FormattedMessage.EscapeText(body.ToUpperInvariant());

        msg.AddMarkupOrThrow($"[font=RobotoMonoBold][color={SenderColor.ToHex()}]{senderText}[/color][/font]");
        msg.AddMarkupOrThrow(
            $"[font=RobotoMono][color={SeparatorColor.ToHex()}] > [/color][color={MintDim.ToHex()}]{bodyText}[/color][/font]\n");
    }

    private static (string Sender, string Body) SplitMessage(string raw)
    {
        if (raw.StartsWith('['))
        {
            var end = raw.IndexOf("]: ", StringComparison.Ordinal);
            if (end > 1)
                return (raw[1..end], raw[(end + 3)..]);
        }

        var separator = raw.IndexOf(" > ", StringComparison.Ordinal);
        if (separator > 0)
            return (raw[..separator], raw[(separator + 3)..]);

        return ("ВЕСТОН-ЯМАДА", raw);
    }
}
