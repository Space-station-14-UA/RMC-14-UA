using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._Mriya.Monitoring;

[GenerateTypedNameReferences]
public sealed partial class MRMonitoringRosterRow : ContainerButton
{
    private static readonly StyleBoxFlat NormalStyle = new()
    {
        BackgroundColor = Color.FromHex("#06180D"),
        BorderColor = Color.FromHex("#154D28"),
        BorderThickness = new Thickness(1),
        ContentMarginLeftOverride = 0,
        ContentMarginTopOverride = 0,
        ContentMarginRightOverride = 0,
        ContentMarginBottomOverride = 0,
    };

    private static readonly StyleBoxFlat HoverStyle = new()
    {
        BackgroundColor = Color.FromHex("#0B2A16"),
        BorderColor = Color.FromHex("#2E9E57"),
        BorderThickness = new Thickness(1),
        ContentMarginLeftOverride = 0,
        ContentMarginTopOverride = 0,
        ContentMarginRightOverride = 0,
        ContentMarginBottomOverride = 0,
    };

    private static readonly StyleBoxFlat SelectedStyle = new()
    {
        BackgroundColor = Color.FromHex("#0F3A1E"),
        BorderColor = Color.FromHex("#5CFF8A"),
        BorderThickness = new Thickness(3, 1, 1, 1),
        ContentMarginLeftOverride = 0,
        ContentMarginTopOverride = 0,
        ContentMarginRightOverride = 0,
        ContentMarginBottomOverride = 0,
    };

    private bool _selected;
    private bool _xamlLoaded;

    public NetEntity Marine;

    public bool IsSelected
    {
        get => _selected;
        set
        {
            _selected = value;
            UpdateVisualState();
        }
    }

    public MRMonitoringRosterRow()
    {
        RobustXamlLoader.Load(this);
        StyleBoxOverride = new StyleBoxEmpty();
        Mode = ActionMode.Press;
        _xamlLoaded = true;
        UpdateVisualState();
    }

    public void SetData(string name, string state, string area, Color stateColor)
    {
        NameLabel.Text = name;
        StateLabel.Text = state;
        StateLabel.FontColorOverride = stateColor;
        AreaLabel.Text = area;
    }

    protected override void DrawModeChanged()
    {
        base.DrawModeChanged();
        UpdateVisualState();
    }

    private void UpdateVisualState()
    {
        if (!_xamlLoaded)
            return;

        if (_selected)
        {
            Background.PanelOverride = SelectedStyle;
            NameLabel.FontColorOverride = Color.FromHex("#7CFFA8");
        }
        else if (DrawMode == DrawModeEnum.Hover)
        {
            Background.PanelOverride = HoverStyle;
            NameLabel.FontColorOverride = Color.White;
        }
        else
        {
            Background.PanelOverride = NormalStyle;
            NameLabel.FontColorOverride = Color.FromHex("#CFFFD9");
        }
    }
}
