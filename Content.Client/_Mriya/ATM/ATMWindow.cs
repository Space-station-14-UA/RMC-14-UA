using System.Numerics;
using Content.Shared._Mriya.ATM;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.ResourceManagement;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.IoC;
using Robust.Shared.Maths;
using Robust.Shared.Prototypes;

namespace Content.Client._Mriya.ATM;

[GenerateTypedNameReferences]
public sealed partial class ATMWindow : DefaultWindow
{
    public event Action<int, int>? OnBuy;
    public event Action<int>? OnWithdraw;

    public Func<EntProtoId, List<Texture>>? PreviewResolver;

    private static readonly Color White = Color.FromHex("#FFFFFF");
    private static readonly Color Mint = Color.FromHex("#BFF3D4");
    private static readonly Color MintLight = Color.FromHex("#E0FBEA");
    private static readonly Color MintDim = Color.FromHex("#6FBF93");
    private static readonly Color Yellow = Color.FromHex("#FFD84D");
    private static readonly Color GreenDim = Color.FromHex("#0A8A0A");

    private readonly Font _font;
    private readonly Font _fontSmall;
    private readonly Font _fontTitle;
    private readonly Font _fontLarge;

    private readonly StyleBoxFlat _buttonBox;
    private readonly StyleBoxFlat _tabBox;
    private readonly StyleBoxFlat _tabActiveBox;
    private readonly StyleBoxFlat _lineEditBox;

    private ATMBuiState? _state;
    private readonly List<Button> _tabs = new();
    private int _category;
    private int _entry;

    public ATMWindow()
    {
        RobustXamlLoader.Load(this);

        var cache = IoCManager.Resolve<IResourceCache>();
        _font = new VectorFont(cache.GetResource<FontResource>("/Fonts/RobotoMono/RobotoMono-Regular.ttf"), 12);
        _fontSmall = new VectorFont(cache.GetResource<FontResource>("/Fonts/RobotoMono/RobotoMono-Regular.ttf"), 10);
        _fontTitle = new VectorFont(cache.GetResource<FontResource>("/Fonts/RobotoMono/RobotoMono-Bold.ttf"), 12);
        _fontLarge = new VectorFont(cache.GetResource<FontResource>("/Fonts/RobotoMono/RobotoMono-Bold.ttf"), 16);

        _buttonBox = MakeBox(Color.FromHex("#07240F"), Color.FromHex("#12602E"), 8, 4);
        _tabBox = MakeBox(Color.FromHex("#0A2415"), Color.FromHex("#0F3F22"), 8, 4);
        _tabActiveBox = MakeBox(Color.FromHex("#0E4A22"), GreenDim, 8, 4);
        _lineEditBox = MakeBox(Color.FromHex("#06180D"), Color.FromHex("#12602E"), 6, 3);

        foreach (var label in new[]
                 {
                     LinkLabel, OperativeLabel, StatusLabel,
                 })
        {
            label.FontOverride = _font;
            label.FontColorOverride = Mint;
        }

        SloganLabel.FontOverride = _fontSmall;
        SloganLabel.FontColorOverride = Mint;

        OperativeNameLabel.FontOverride = _font;
        OperativeNameLabel.FontColorOverride = MintLight;

        BalanceLabel.FontOverride = _font;
        BalanceLabel.FontColorOverride = Yellow;

        ItemPriceLabel.FontOverride = _font;
        ItemPriceLabel.FontColorOverride = Yellow;

        TerminalLabel.FontOverride = _fontTitle;
        TerminalLabel.FontColorOverride = White;

        ItemNameLabel.FontOverride = _fontLarge;
        ItemNameLabel.FontColorOverride = White;

        LinkLabel.FontColorOverride = MintDim;

        StyleButton(WithdrawButton, _buttonBox, Mint);
        StyleButton(BuyButton, _buttonBox, Mint);
        StyleButton(PrevButton, _buttonBox, Mint);
        StyleButton(NextButton, _buttonBox, Mint);
        WithdrawAmount.StyleBoxOverride = _lineEditBox;

        Logo.Texture = cache.GetResource<TextureResource>("/Textures/_Mriya/Interface/Logo/weyland-yamada.png").Texture;
        Logo.TextureScale = new Vector2(0.32f, 0.32f);
        Logo.Modulate = new Color(0.72f, 0.80f, 0.75f, 0.9f);

        WithdrawButton.OnPressed += _ => Withdraw();
        BuyButton.OnPressed += _ => Buy();
        PrevButton.OnPressed += _ => Cycle(-1);
        NextButton.OnPressed += _ => Cycle(1);
    }

    private static StyleBoxFlat MakeBox(Color background, Color border, float horizontal, float vertical)
    {
        var box = new StyleBoxFlat
        {
            BackgroundColor = background,
            BorderColor = border,
            BorderThickness = new Thickness(1),
        };

        box.ContentMarginLeftOverride = horizontal;
        box.ContentMarginRightOverride = horizontal;
        box.ContentMarginTopOverride = vertical;
        box.ContentMarginBottomOverride = vertical;
        return box;
    }

    private void StyleButton(Button button, StyleBox style, Color color, bool bold = false)
    {
        button.StyleBoxOverride = style;
        button.Label.FontOverride = bold ? _fontTitle : _font;
        button.Label.FontColorOverride = color;
    }

    private void Buy()
    {
        if (_state == null || _category < 0 || _category >= _state.Categories.Count)
            return;

        var entries = _state.Categories[_category].Entries;
        if (_entry < 0 || _entry >= entries.Count)
            return;

        OnBuy?.Invoke(_category, _entry);
    }

    private void Withdraw()
    {
        if (!int.TryParse(WithdrawAmount.Text, out var amount))
            return;

        OnWithdraw?.Invoke(amount);
    }

    private void Cycle(int direction)
    {
        if (_state == null || _category < 0 || _category >= _state.Categories.Count)
            return;

        var count = _state.Categories[_category].Entries.Count;
        if (count == 0)
            return;

        _entry = ((_entry + direction) % count + count) % count;
        RefreshEntry();
    }

    public void SetState(ATMBuiState state)
    {
        _state = state;
        BalanceLabel.Text = $"${state.Balance}";
        OperativeLabel.Text = "ОПЕРАТИВНИК";
        OperativeNameLabel.Text = state.UserName.ToUpperInvariant();
        LinkLabel.Text = $"ТЕРМІНАЛ {state.TerminalNumber:00} // {state.MapName} // КАНАЛ: {state.LinkCode}";

        BuildTabs();

        if (_category >= state.Categories.Count)
            _category = 0;

        var entryCount = state.Categories.Count > 0 ? state.Categories[_category].Entries.Count : 0;
        if (_entry >= entryCount)
            _entry = 0;

        RefreshTabs();
        RefreshEntry();
    }

    private void BuildTabs()
    {
        CategoryTabs.RemoveAllChildren();
        _tabs.Clear();

        if (_state == null)
            return;

        for (var i = 0; i < _state.Categories.Count; i++)
        {
            var index = i;
            var button = new Button
            {
                Text = _state.Categories[i].Name.ToUpperInvariant(),
                Margin = new Thickness(0, 0, 4, 0),
            };
            StyleButton(button, _tabBox, MintDim);
            button.OnPressed += _ =>
            {
                _category = index;
                _entry = 0;
                RefreshTabs();
                RefreshEntry();
            };

            _tabs.Add(button);
            CategoryTabs.AddChild(button);
        }
    }

    private void RefreshTabs()
    {
        for (var i = 0; i < _tabs.Count; i++)
        {
            var active = i == _category;
            _tabs[i].StyleBoxOverride = active ? _tabActiveBox : _tabBox;
            _tabs[i].Label.FontColorOverride = active ? Mint : MintDim;
        }
    }

    private void RefreshEntry()
    {
        if (_state == null || _category < 0 || _category >= _state.Categories.Count)
            return;

        var entries = _state.Categories[_category].Entries;
        if (entries.Count == 0)
        {
            ItemNameLabel.Text = "// НЕМАЄ ТОВАРІВ //";
            ItemPriceLabel.Text = string.Empty;
            StatusLabel.Text = string.Empty;
            Preview.Textures = new List<Texture>();
            BuyButton.Disabled = true;
            return;
        }

        var entry = entries[_entry];
        ItemNameLabel.Text = entry.Name.ToUpperInvariant();
        ItemPriceLabel.Text = $"${entry.Cost}";
        StatusLabel.Text = $"[ {_entry + 1} / {entries.Count} ]";

        Preview.Textures = PreviewResolver?.Invoke(entry.Preview) ?? new List<Texture>();

        var affordable = _state.Balance >= entry.Cost;
        BuyButton.Disabled = !affordable;
    }
}
