#!/usr/bin/env python3
"""
Generates Contact store entries for SPECIAL magazines (AP / Ext / HEAP / other)
that fit the guns already sold in the Contact store.

How it decides:
- Guns    = protos of contactStoreEntry in the long/short arms folders.
- Fits    = magazine's Tag tags intersect the gun's `gun_magazine` slot whitelist tags
            (parents/inheritance resolved).
- Special = a compatible magazine whose id extends another compatible magazine's id
            (CMMagazineRifleM4SPR -> CMMagazineRifleM4SPRAP). The base magazine itself is skipped.
- Price   = HEAP 10, AP/Ext 6, any other special 8. Pistol magazines: half, rounded up.
- Magazines already in a store entry are skipped.

Run from the repo root:
    python gen_contact_mags.py
Writes Resources/Prototypes/_Mriya/Contact/contact_store_magazines.yml
"""
import math
import sys
from pathlib import Path

import yaml

PROTOS = Path("Resources/Prototypes")
STORE_DIR = PROTOS / "_Mriya" / "Contact"
OUT = STORE_DIR / "contact_store_magazines.yml"

GUN_CATEGORIES = {"MRContactStoreLongArms", "MRContactStoreShortArms"}
PISTOL_CATEGORIES = {"MRContactStoreShortArms"}
AMMO_CATEGORY = "MRContactStoreAmmo"
MAG_SLOT = "gun_magazine"


# ── YAML loading (SS14 files use custom !type: tags) ──

class Loader(yaml.SafeLoader):
    pass


def _any_tag(loader, _suffix, node):
    if isinstance(node, yaml.MappingNode):
        return loader.construct_mapping(node, deep=True)
    if isinstance(node, yaml.SequenceNode):
        return loader.construct_sequence(node, deep=True)
    return loader.construct_scalar(node)


Loader.add_multi_constructor("!", _any_tag)


def load_docs(path):
    try:
        with open(path, encoding="utf-8") as f:
            data = yaml.load(f, Loader=Loader)
    except Exception as e:  # noqa: BLE001
        print(f"skip {path}: {e}", file=sys.stderr)
        return []
    return data if isinstance(data, list) else []


# ── Prototype inheritance ──

def deep_merge(base, over):
    if isinstance(base, dict) and isinstance(over, dict):
        out = dict(base)
        for k, v in over.items():
            out[k] = deep_merge(base[k], v) if k in base else v
        return out
    return over


entities = {}
store_entries = []

for path in PROTOS.rglob("*.yml"):
    if path.resolve() == OUT.resolve():
        continue
    for doc in load_docs(path):
        if not isinstance(doc, dict):
            continue
        if doc.get("type") == "entity" and "id" in doc:
            entities[doc["id"]] = doc
        elif doc.get("type") == "contactStoreEntry":
            store_entries.append(doc)

_resolved = {}


def resolve(eid, stack=()):
    """Returns {component type: merged data} for an entity, parents included."""
    if eid in _resolved:
        return _resolved[eid]
    entry = entities.get(eid)
    if entry is None or eid in stack:
        return {}

    comps = {}
    parents = entry.get("parent") or []
    if isinstance(parents, str):
        parents = [parents]
    for parent in parents:
        for ctype, data in resolve(parent, stack + (eid,)).items():
            comps[ctype] = deep_merge(comps.get(ctype, {}), data)

    for comp in entry.get("components") or []:
        if isinstance(comp, dict) and "type" in comp:
            data = {k: v for k, v in comp.items() if k != "type"}
            comps[comp["type"]] = deep_merge(comps.get(comp["type"], {}), data)

    _resolved[eid] = comps
    return comps


def mag_whitelist_tags(gun_id):
    comps = resolve(gun_id)
    slot = (comps.get("ItemSlots", {}).get("slots", {}) or {}).get(MAG_SLOT, {}) or {}
    return set((slot.get("whitelist", {}) or {}).get("tags", []) or [])


def tags_of(eid):
    return set((resolve(eid).get("Tag", {}) or {}).get("tags", []) or [])


# ── Collect ──

already_sold = {e.get("proto") for e in store_entries}
guns = [(e["proto"], e.get("category")) for e in store_entries if e.get("category") in GUN_CATEGORIES]

magazines = [
    eid for eid, e in entities.items()
    if not e.get("abstract")
    and "Empty" not in eid
    and "BallisticAmmoProvider" in resolve(eid)
    and "Gun" not in resolve(eid)
]

out_lines = [
    "# GENERATED by gen_contact_mags.py: special magazines for guns sold in the Contact store.",
    "# Pricing: HEAP 10, AP/Ext 6, other special 8, pistol magazines half (rounded up).",
    "",
]
added = set()

for gun, category in guns:
    wl = mag_whitelist_tags(gun)
    if not wl:
        continue

    compatible = sorted(m for m in magazines if tags_of(m) & wl)
    if not compatible:
        continue

    block = []
    for mag in compatible:
        # base = longest other compatible id this one extends
        bases = [b for b in compatible if b != mag and mag.startswith(b)]
        if not bases:
            continue  # it's a base magazine, not special

        base = max(bases, key=len)
        suffix = mag[len(base):]

        if mag in already_sold or mag in added:
            continue

        if "HEAP" in suffix:
            price = 10
        elif suffix.startswith("AP") or suffix.startswith("Ext"):
            price = 6
        else:
            price = 8

        if "Pistol" in mag or category in PISTOL_CATEGORIES:
            price = math.ceil(price / 2)

        added.add(mag)
        block += [
            "- type: contactStoreEntry",
            f"  id: MRContactStore{mag}",
            f"  proto: {mag}",
            f"  category: {AMMO_CATEGORY}",
            f"  price: {price}",
            "",
        ]

    if block:
        out_lines.append(f"# {gun}")
        out_lines += block

OUT.parent.mkdir(parents=True, exist_ok=True)
OUT.write_text("\n".join(out_lines), encoding="utf-8")
print(f"wrote {len(added)} magazines to {OUT}")
